export function generateDailyVerse(): { text: string; ref: string } {
  const d = new Date();
  const dayNum = Math.floor(Date.UTC(d.getFullYear(), d.getMonth(), d.getDate()) / 86400000);
  return dailyVerses[dayNum % dailyVerses.length];
}

