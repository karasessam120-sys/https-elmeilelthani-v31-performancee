    return 'الصلاة هي محادثة مع الله. ابدأ بتسبيحه، ثم اشكره على نِعَمه، ثم اطلب ما تحتاجه بثقة. قال يسوع: «مهما طلبتم باسمي فهذا أفعله ليتمجد الآب بالابن» (يوحنا 14: 13). صلِّ بقلب بسيط وصادق — الله يسمعك!';
