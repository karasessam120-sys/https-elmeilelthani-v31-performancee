export function getAIResponse(userMessage: string): string {
  const lower = userMessage.toLowerCase().trim();

  for (const entry of knowledgeBase) {
    for (const keyword of entry.keywords) {
      if (lower.includes(keyword)) {
        return entry.response;
      }
    }
  }

  if (lower.includes('hello') || lower.includes('hi ') || lower === 'hi' || lower.includes('سلام') || lower.includes('مرحبا') || lower.includes('اهلا') || lower.includes('أهلا') || lower.includes('السلام') || lower.includes('peace')) {
    return 'مرحباً يا صديقي العزيز! أنا رفيق النور، رفيقك في رحلة الإيمان. أنا هنا لمساعدتك في فهم الكلمات والآيات الصعبة في الكتاب المقدس. اسألني عن أي مصطلح من الكتاب — النعمة، الإيمان، الفداء، التثليث، أو أي شيء آخر — وسأشرحه لك ببساطة ووضوح!';
  }

  if (lower.includes('thank') || lower.includes('شكرا') || lower.includes('شكراً') || lower.includes('متشكر')) {
    return 'العفو يا صديقي! من فرحي أن أسير معك في فهم كلمة الله. تذكّر: «سراج لرجلي كلامك ونور لسبيلي» (مزمور 119: 105). اسألني في أي وقت وعن أي شيء!';
  }

  if (lower.includes('help') || lower.includes('what can you') || lower.includes('ساعد') || lower.includes('ماذا تقدر') || lower.includes('تقدر تعمل')) {
    return 'أنا رفيق النور، رفيقك الذكي للدراسة! أستطيع شرح كلمات وآيات الكتاب المقدس بلغة بسيطة ودودة. جرّب أن تسألني عن: النعمة، الإيمان، الفداء، التبرير، التقديس، التثليث، الأمثال، ملكوت الله، التوبة، المعمودية، التناول، أو أي آية تحيّرك! أو اسألني «ماذا أقرأ اليوم؟» أو «كيف أصلي؟»';
  }

  // Try general conversation for non-biblical questions
  const generalResponse = getGeneralChatResponse(userMessage);
  if (generalResponse) return generalResponse;

  const idx = Math.floor(Math.random() * fallbackResponses.length);
  return fallbackResponses[idx];
}

